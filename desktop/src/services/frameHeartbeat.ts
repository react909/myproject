/**
 * Отметка «страница всё ещё рисуется».
 *
 * Зачем. Самая частая жалоба на кассу — «постояла несколько часов, и экран
 * белый». Ни сна, ни падения при этом не было: рендерер жив и на любой вопрос
 * отвечает, а рисовать перестал — потерялась поверхность окна. Опросом такое не
 * поймать, поймать можно только по кадрам.
 *
 * Отсюда и способ: отметка ставится из `requestAnimationFrame`, то есть ровно
 * тогда, когда браузер действительно готовит кадр. Встала отрисовка — встали и
 * отметки, и главный процесс это увидит (electron/services/resilience.cjs).
 * Таймер для этого не годится: `setInterval` продолжает идти и в окне, которое
 * давно ничего не показывает.
 *
 * Стоимость близка к нулю: цикл кадров в приложении и так крутится, а наружу
 * уходит одно сообщение раз в две секунды.
 */

/** Как часто уходит отметка. Должно совпадать с HEARTBEAT_EVERY_MS в resilience.cjs. */
const EVERY_MS = 2000

/**
 * Запускает отметки. Возвращает функцию остановки.
 *
 * Вне Electron (браузер, тесты) ничего не делает: там нет ни главного процесса,
 * ни белого экрана, который он лечит.
 */
export function startFrameHeartbeat(): () => void {
  const beat = window.powerAPI?.heartbeat
  if (typeof beat !== 'function') return () => undefined

  let frame = 0
  let last = 0

  const tick = (now: number) => {
    // Кадры идут по 60 раз в секунду — сообщение отправляется не на каждом.
    if (now - last >= EVERY_MS) {
      last = now
      beat()
    }
    frame = window.requestAnimationFrame(tick)
  }

  frame = window.requestAnimationFrame(tick)
  return () => window.cancelAnimationFrame(frame)
}

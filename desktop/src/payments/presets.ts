/**
 * Пресеты платёжных систем.
 *
 * Пресет — это заготовка настройки, а не отдельная реализация: все банки
 * разговаривают через один и тот же адаптер динамического QR, отличаясь
 * адресом и тем, как называется их payload. Поэтому «добавить банк» здесь
 * буквально означает дописать запись в массив.
 *
 * ELQR стоит первым осознанно. Это национальная система межбанковского
 * процессингового центра: один QR принимают приложения всех подключённых
 * банков, и интеграция с ней снимает необходимость договариваться с каждым
 * банком отдельно. Для продукта это правильная цель, остальные пресеты —
 * запасной путь для магазина, у которого уже есть договор с конкретным банком.
 */

export type PaymentPresetId = 'elqr' | 'mbank' | 'bakai' | 'optima' | 'custom'

export type PaymentPreset = {
  id: PaymentPresetId
  title: string
  /** Одна строка о том, что даёт этот выбор. */
  note: string
  /**
   * Адрес API по умолчанию. Пустая строка означает, что боевой адрес выдаёт
   * банк при подключении: придумывать его за него нельзя — касса молча
   * стучалась бы не туда.
   */
  baseUrl: string
}


/**
 * Скелетон разделов кабинета.
 *
 * Не украшение. Финансы и аналитика считают выручку по всей базе, и на кассе с
 * годовой историей первый кадр приходит не мгновенно. Пустой белый прямоугольник
 * в этот момент читается как «раздел сломался», и человек уходит со страницы
 * ровно перед тем, как она нарисуется.
 *
 * Форма повторяет то, что появится: строка плиток сверху, широкий блок графика,
 * список под ним. Скелетон, не совпадающий с будущей раскладкой, хуже
 * отсутствия скелетона — он обещает одно, а показывает другое, и переход
 * выглядит как подмена страницы.
 *
 * Мерцание — на opacity: раскладку оно не трогает, поэтому не отнимает кадры у
 * данных, которые в этот момент считаются.
 */

type Props = {
  /** Сколько строк в нижнем списке — у разных разделов они разной длины. */
  rows?: number
  /** Раздел без графика: у сотрудников его нет, и место под него пустовало бы. */
  chart?: boolean
}

export function OwnerSkeleton({ rows = 5, chart = true }: Props) {
  return (
    <div className="ocab-skeleton" role="status" aria-label="Загрузка раздела">
      <div className="ocab-skeleton__tiles">
        {[0, 1, 2, 3].map((index) => (
          <div key={index} className="ocab-skeleton__tile" />
        ))}
      </div>

      {chart && <div className="ocab-skeleton__chart" />}

      <div className="ocab-skeleton__list">
        {Array.from({ length: rows }, (_, index) => (
          <div key={index} className="ocab-skeleton__row" />
        ))}
      </div>
    </div>
  )
}

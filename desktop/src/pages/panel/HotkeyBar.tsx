/**
 * Полоса подсказок клавиш внизу экрана.
 *
 * Это рабочий инструмент, а не украшение. Человек за этой системой работает
 * стрелками, и полоса отвечает на единственный вопрос, который у него есть в
 * каждый момент: что здесь делает F4. Держать это в голове по всем разделам
 * нельзя, а искать в справке — значит не пользоваться клавишами вовсе.
 *
 * Полоса МЕНЯЕТСЯ ПО МЕСТУ. Набор в списке документов и набор в открытой
 * накладной разные, и показывать общий набор «на все случаи» бессмысленно:
 * половина подписей будет врать. Поэтому подсказки приходят от того, кто
 * сейчас на экране, а полоса их только рисует.
 *
 * Заодно это та самая узнаваемая черта, которая отличает систему от типового
 * интерфейса: так выглядят торговые и складские программы, с которыми человек
 * уже работал.
 */

import './HotkeyBar.css'

export type Hotkey = {
  /** Обозначение клавиши: F2, Ins, Esc, ↑↓. */
  keys: string
  /** Что она делает. Одно-два слова: полоса высотой 26 px, длинное не влезет. */
  action: string
  /** Недоступна сейчас — показывается приглушённой, но не исчезает.
   *
   * Исчезающие подсказки хуже неактивных: набор скачет при каждом движении по
   * таблице, и глаз перестаёт находить нужную по её месту в ряду. */
  off?: boolean
}

type Props = {
  hotkeys: readonly Hotkey[]
  /** Что-нибудь короткое справа: состояние, счётчик, имя открытого документа. */
  status?: string
}

export function HotkeyBar({ hotkeys, status }: Props) {
  return (
    <div className="hkb" role="toolbar" aria-label="Клавиши раздела">
      <div className="hkb__list">
        {hotkeys.map((item) => (
          <span
            key={item.keys + item.action}
            className={`hkb__item${item.off ? ' hkb__item--off' : ''}`}
          >
            <kbd className="hkb__key">{item.keys}</kbd>
            <span className="hkb__action">{item.action}</span>
          </span>
        ))}
      </div>
      {status && <span className="hkb__status">{status}</span>}
    </div>
  )
}

/**
 * Стоит ли касса на сенсорном моноблоке без физической клавиатуры.
 *
 * Одно место на всё приложение: окна ввода секретов решают по нему, показывать
 * ли собственную экранную клавиатуру. Пока этот вопрос решался «на глаз» —
 * клавиатура рисовалась всегда, — она занимала пол-экрана на установках с
 * обычной клавиатурой, где не нужна вовсе.
 *
 * Значение приходит с реквизитами магазина: галочку ставит специалист на первом
 * шаге мастера, сервер держит её в группе `branding` за своей дверью, а сюда
 * она попадает через тот же кэш, из которого печатается чек. Отдельного запроса
 * нет намеренно — окно ключа открывается по жесту и ждать сеть не может.
 *
 * `refresh: false` — за свежестью следит владелец кэша. Дёргать сервер в момент
 * открытия окна значит либо задержать его появление, либо перерисовать
 * клавиатуру под пальцем уже после того, как человек начал набирать.
 */

import { useOnboarding } from '../onboarding/useOnboarding'

export function useTouchScreen(): boolean {
  return useOnboarding({ refresh: false }).branding.touchScreen
}

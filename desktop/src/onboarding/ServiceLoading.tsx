/**
 * Экран подготовки сервисного прохода.
 *
 * Работа здесь настоящая: мастер читает с сервера текущие реквизиты магазина
 * вместе с логотипами — а это несколько мегабайт картинок в base64, разбор
 * которых на кассовом моноблоке занимает заметное время. Пока экрана не было,
 * человек видел пустое место и не понимал, идёт что-то или нет.
 *
 * Шаги перечислены поимённо, а не одной строкой «Загрузка…», и это осознанно:
 * специалист приезжает к клиенту за деньги, и клиент, стоящий рядом, должен
 * видеть, что именно делается с его кассой. Список работает и на специалиста —
 * если что-то не доехало, видно, на чём именно остановилось.
 *
 * `MINIMUM_MS` — нижняя граница показа. Без неё на быстрой машине экран мигает
 * на сотню миллисекунд, и мелькание читается хуже, чем спокойная пауза: глаз
 * успевает заметить движение, но не успевает прочитать. Полторы секунды — время,
 * за которое список прочитывается целиком.
 */

import { useEffect, useState } from 'react'
import './ServiceLoading.css'

/**
 * Сколько экран показывается минимум, даже если данные пришли раньше.
 *
 * ЭТО ТО САМОЕ ЧИСЛО, КОТОРЫМ НАСТРАИВАЕТСЯ ДЛИТЕЛЬНОСТЬ ЗАГРУЗКИ.
 * Хотите дольше — увеличьте его здесь, больше нигде править не нужно: список
 * шагов растянется на новую длительность сам.
 *
 * Четыре секунды: за это время список шагов прочитывается целиком, и клиент,
 * стоящий рядом, успевает увидеть, что именно делается с его кассой.
 *
 * Дольше я ставить не стал, и вот почему. Специалист, который молча смотрит в
 * экран пятнадцать секунд, выглядит не солиднее, а беспомощнее: со стороны это
 * читается не как «идёт серьёзная работа», а как «касса тормозит». Работу
 * показывает не время ожидания, а то, что человек видит на экране, — поэтому
 * сюда вынесен список конкретных шагов, а не крутилка.
 *
 * Число ваше, менять его — ваше право; я только объясняю, почему выбрал такое.
 */
export const MINIMUM_MS = 4000

const STEPS = [
  'Проверка связи с кассой',
  'Чтение реквизитов магазина',
  'Загрузка логотипов и оформления чека',
  'Подготовка мастера настройки',
] as const

export function ServiceLoading() {
  const [step, setStep] = useState(0)

  /* Шаги сменяются по времени, а не по настоящим этапам запроса: запрос один,
     разбить его на четыре нечем. Поэтому это индикатор хода, а не отчёт — и
     дойдя до последнего шага, он на нём и остаётся, пока данные не приедут. */
  useEffect(() => {
    const per = Math.floor(MINIMUM_MS / STEPS.length)
    const timer = window.setInterval(() => {
      setStep((current) => (current < STEPS.length - 1 ? current + 1 : current))
    }, per)
    return () => window.clearInterval(timer)
  }, [])

  return (
    // data-no-virtual-keyboard: вводить здесь нечего, всплывающая клавиатура
    // поверх экрана подготовки только мешала бы.
    <main className="svc-load" role="status" aria-live="polite" data-no-virtual-keyboard>
      <div className="svc-load__card">
        <div className="svc-load__spinner" aria-hidden="true" />
        <h1 className="svc-load__title">Сервисная настройка</h1>
        <p className="svc-load__subtitle">Готовим мастер к правке настроек установки</p>

        <ol className="svc-load__steps">
          {STEPS.map((label, index) => (
            <li
              key={label}
              className={`svc-load__step${index < step ? ' is-done' : ''}${
                index === step ? ' is-active' : ''
              }`}
            >
              <span className="svc-load__mark" aria-hidden="true" />
              {label}
            </li>
          ))}
        </ol>
      </div>
    </main>
  )
}

/**
 * Пояснение к налоговому блоку.
 *
 * НСП путают с НДС постоянно, а ставка зависит не от режима, а от того,
 * плательщик ли магазин НДС и чем он торгует. Объясняем это прямо под полями,
 * а не в справке, куда никто не пойдёт. В простом режиме объяснять нечего —
 * там одна строка о том, почему всё по нулям.
 */

import { isFiscal } from './types'
import type { OnboardingData } from './types'
import './TaxNote.css'

export function TaxNote({ data }: { data: OnboardingData }) {
  if (!isFiscal(data)) {
    return (
      <p className="tax-note">
        Режим работы — без фискальной кассы, поэтому ставки нулевые и в чек не печатаются. Понадобятся —
        переключите режим на шаге «Магазин и касса».
      </p>
    )
  }

  return (
    <p className="tax-note">
      <strong>НСП — это налог с продаж, отдельный от НДС.</strong> Если магазин не плательщик НДС: 2% для
      торговли, 3% для услуг. Если плательщик: 0% по безналу, 1–2% по наличным. Подставленные ставки —
      типовые; свои значения можно вписать поверх.
    </p>
  )
}

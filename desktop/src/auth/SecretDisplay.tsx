/**
 * Показ набранного секрета — точками или символами.
 *
 * Зачем вместо обычного поля. Секрет набирают на экранной клавиатуре, глядя на
 * клавиши, а не на поле: между нажатием и взглядом вверх проходит секунда, и
 * человеку нужно понимать, попал он по клавише или промахнулся. Точки в
 * системном `input[type=password]` появляются без всякого движения, и на
 * моноблоке это выглядит так, будто нажатие не засчиталось.
 *
 * Поэтому каждый символ — своя ячейка, и появляется она с коротким движением:
 * ячейка возникает из уменьшенной и подсвеченной. Движение только на transform
 * и opacity, поэтому раскладка не пересчитывается и набор не подтормаживает
 * даже на слабом моноблоке, где под полем ещё и клавиатура на полсотни клавиш.
 *
 * Настоящий `<input>` при этом никуда не девается: он лежит поверх прозрачным и
 * принимает физическую клавиатуру, выделение и системные жесты. Подменять его
 * своим состоянием нельзя — на установке с обычной клавиатурой это сломало бы
 * привычный ввод ради красоты на моноблоке.
 */

import { useEffect, useRef, useState } from 'react'
import type { CSSProperties } from 'react'

/**
 * Сколько живёт уходящая ячейка.
 *
 * Стёртый символ не исчезает мгновенно: ячейка ещё коротко сжимается и гаснет.
 * Без этого удаление выглядит как сбой отрисовки — было пять кружков, стало
 * четыре, и непонятно, стёрлось одно или два.
 *
 * Должно совпадать с длительностью acc-cell-out в AccessDialog.css.
 */
const EXIT_MS = 160

/**
 * Сколько уходящих ячеек рисуется одновременно.
 *
 * Потолок, а не расчёт: уход длится доли секунды, и больше трёх штук сразу
 * человек всё равно не различит. Зато никакая будущая ошибка в подсчёте не
 * сможет засыпать поле призраками — а именно это уже случилось однажды.
 */
const MAX_LEAVING = 3

type Props = {
  value: string
  /** Показывать символы, а не точки. */
  reveal: boolean
  /** Что нарисовать, пока пусто. У ключа это его маска, у пароля ничего. */
  placeholder?: string
  /** Поле в фокусе — рисуем каретку: своя, потому что системная скрыта. */
  focused: boolean
  /**
   * Идёт проверка.
   *
   * Тогда по набранному бежит волна — ячейки приподнимаются одна за другой.
   * Это не украшение: проверка занимает около полутора десятых секунды, и без
   * движения кажется, что нажатие потерялось. Волна отвечает на «а оно вообще
   * что-то делает?» тем же местом, куда человек в этот момент смотрит, —
   * набранным паролем, а не отдельным индикатором сбоку.
   */
  busy?: boolean
  /**
   * Секрет не подошёл.
   *
   * Тогда кружки коротко мотает из стороны в сторону — «нет». Отдельно от
   * сообщения об ошибке: человек смотрит на набранное, а не читает подпись, и
   * ответ должен прийти туда же, куда направлен взгляд.
   */
  invalid?: boolean
}

export function SecretDisplay({
  value,
  reveal,
  placeholder,
  focused,
  busy = false,
  invalid = false,
}: Props) {
  const characters = [...value]

  /**
   * Сколько ячеек сейчас «уходит».
   *
   * React убирает лишние узлы сразу, и анимировать уход обычным способом
   * нечему — элемента уже нет в дереве. Поэтому стёртые ячейки рисуются ещё
   * `EXIT_MS` отдельно, после живых, и только потом пропадают.
   *
   * Хранится число, а не сами символы: уходящая ячейка рисуется пустым
   * кружком, и знать, какой символ в ней был, не нужно — тем более что это
   * секрет.
   *
   * ВАЖНО: таймер удаления не отменяется при новом наборе, и это исправление
   * настоящей ошибки. Пока уборка эффекта его отменяла, каждое следующее
   * нажатие отменяло удаление предыдущего призрака — они копились навсегда, а
   * во время проверки на каждом висела бесконечная анимация волны. Со стороны
   * это выглядело как лишние кружки рядом с текстом и жестокие тормоза.
   */
  const [leaving, setLeaving] = useState(0)
  const previousCount = useRef(characters.length)
  const aliveRef = useRef(true)

  useEffect(() => {
    aliveRef.current = true
    return () => {
      aliveRef.current = false
    }
  }, [])

  useEffect(() => {
    const removed = previousCount.current - characters.length
    previousCount.current = characters.length
    if (removed <= 0) return
    // Потолок: даже если что-то пойдёт не так, призраков не станет больше
    // горстки — ни на вид, ни по нагрузке.
    setLeaving((current) => Math.min(MAX_LEAVING, current + removed))
    window.setTimeout(() => {
      if (aliveRef.current) setLeaving((current) => Math.max(0, current - removed))
    }, EXIT_MS)
  }, [characters.length])

  return (
    // aria-hidden: значение уже несёт настоящее поле ввода, и озвучивать его
    // дважды — значит диктовать секрет вслух по буквам.
    <div
      className={`acc-cells${busy ? ' is-checking' : ''}${invalid ? ' is-invalid' : ''}`}
      aria-hidden="true"
    >
      {characters.length === 0 && placeholder && (
        <span className="acc-cells__placeholder">{placeholder}</span>
      )}

      {characters.map((character, index) => (
        /*
          Ключ — позиция, и это осознанно. При дописывании в конец монтируется
          ровно одна новая ячейка, и движение проигрывается только у неё:
          соседние не трогаются и не мигают. Ключ по символу давал бы обратное —
          два одинаковых символа подряд React счёл бы одним и тем же.
        */
        <span
          key={index}
          className={`acc-cell${character === '-' ? ' acc-cell--sep' : ''}`}
          /* Задержка волны — по месту в ряду: каждая следующая ячейка
             приподнимается чуть позже соседней, и по паролю бежит волна, а не
             мигает весь ряд разом. Переменная, а не класс: позиций столько же,
             сколько символов, и классов пришлось бы заводить столько же. */
          style={{ '--wave-delay': `${index * 45}ms` } as CSSProperties}
        >
          {reveal ? (
            <span className="acc-cell__char">{character}</span>
          ) : (
            /*
              Кружок из двух частей: контур и заливка внутри него.

              Сначала появляется пустой контур, затем он заполняется изнутри —
              два коротких движения вместо одного. Так набор читается боковым
              зрением, а смотрит человек в этот момент на клавиши, а не в поле.

              Прежней подсветки вокруг точки нет: свечение выглядело как пятно
              краски на пустом месте и мешало больше, чем помогало.
            */
            <span className="acc-cell__dot">
              <i className="acc-cell__fill" />
            </span>
          )}
        </span>
      ))}

      {/*
        Уходящие ячейки: стёртые символы ещё коротко сжимаются и гаснут.

        Только когда секрет скрыт. При нажатой кнопке «Показать» настоящие
        символы — буквы, а призрак нарисовался бы кружком: в поле оказывались
        буквы и кружки вперемешку, и выглядело это как поломка. Что было в
        стёртой ячейке, мы намеренно не помним — нарисовать её буквой нечем.
      */}
      {!reveal &&
        Array.from({ length: leaving }, (_, index) => (
          <span key={`leaving-${index}`} className="acc-cell acc-cell--leaving">
            <span className="acc-cell__dot">
              <i className="acc-cell__fill" />
            </span>
          </span>
        ))}

      {focused && <span className="acc-cells__caret" />}
    </div>
  )
}

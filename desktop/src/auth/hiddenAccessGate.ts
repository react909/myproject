/**
 * Правила трёхступенчатого входа специалиста.
 *
 * Логика вынесена из хука отдельно и без React: это набор правил про время, и
 * проверять их удобнее тестом, а не удержанием логотипа руками по пять секунд.
 *
 * Цепочка, строго в этом порядке:
 *  1. Аккорд `Ctrl+Alt+Shift+S` выдаёт разрешение на `ARM_WINDOW_MS`. Ничего не
 *     открывается и никак не отображается.
 *  2. Пока разрешение действует — `TAP_COUNT` быстрых тапов по часам, все
 *     внутри `TAP_WINDOW_MS`. Разрешение при этом тратится и заменяется правом
 *     на удержание — `HOLD_WINDOW_MS`.
 *  3. Пока действует право на удержание — удержание логотипа `holdMs`
 *     открывает окно ключа. Первые `HOLD_HINT_FROM` времени не показывается
 *     ничего, дальше знак едва заметно темнеет.
 *
 * Главное свойство: каждое звено работает только после предыдущего. Без аккорда
 * тапы не считаются вовсе, без тапов удержание не начинается — ни отсчёта, ни
 * реакции, ни подсказки, сколько бы ни держали.
 *
 * Зачем цепочка. Одно удержание логотипа рано или поздно находит любопытный
 * кассир: знак на виду, а удержание — первое, что пробуют на сенсорном экране.
 * Один аккорд легко подсмотреть из-за плеча. Три разнородных действия подряд,
 * каждое со своим окном, не воспроизводятся ни случайно, ни подглядыванием.
 *
 * Все звенья одноразовые: сработал жест, закрыли окно, истекло время или
 * перезапустили приложение — начинать надо с аккорда.
 */

/**
 * Сколько живёт взведённое ожидание.
 *
 * Полминуты — время, за которое человек убирает руку с клавиатуры и находит
 * логотип пальцем. Дольше нельзя: забытый взвод превращает жест обратно в
 * «просто подержи логотип», от которого мы и уходим.
 */
export const ARM_WINDOW_MS = 30_000

/**
 * С какой доли удержания знак начинает темнеть — три секунды из пяти.
 *
 * Первые секунды не происходит ничего: случайное касание не должно ничего
 * выдавать. Дальше намёк нужен тому, кто держит осознанно, — иначе он отпустит
 * логотип, решив, что не сработало.
 */
export const HOLD_HINT_FROM = 0.6

/**
 * Сколько тапов по часам нужно и за какое время.
 *
 * Часы выбраны намеренно: по ним не нажимают случайно, в отличие от плиток «К
 * оплате» и кнопок шапки. Пять тапов за три секунды — это заметно быстрее, чем
 * человек трогает часы из любопытства, и заведомо медленнее дребезга сенсора.
 */
export const TAP_COUNT = 5
export const TAP_WINDOW_MS = 3000

/**
 * Сколько живёт право на удержание после серии тапов.
 *
 * Отдельное окно, а не остаток от аккорда. Иначе серия, набранная на двадцать
 * девятой секунде, оставляла бы на поиск логотипа одну секунду — и специалист,
 * сделавший всё правильно, упирался бы в молчание.
 */
export const HOLD_WINDOW_MS = 30_000

export type GateState = {
  /** До какого времени действует разрешение от аккорда. 0 — не выдано. */
  armedUntil: number
  /** До какого времени действует право на удержание. 0 — не выдано. */
  holdUntil: number
}

export function createGateState(): GateState {
  return { armedUntil: 0, holdUntil: 0 }
}

/**
 * Аккорд специалиста: выдаём разрешение.
 *
 * Прежнее состояние не читается намеренно: повторный аккорд начинает цепочку
 * заново, а не продлевает старую и не перепрыгивает через тапы.
 */
export function arm(_state: GateState, now: number): GateState {
  return { armedUntil: now + ARM_WINDOW_MS, holdUntil: 0 }
}

export function disarm(): GateState {
  return createGateState()
}

/** Действует ли разрешение от аккорда — то есть считать ли тапы. */
export function isArmed(state: GateState, now: number): boolean {
  return state.armedUntil > now
}

/**
 * Серия тапов набрана: разрешение тратится, взамен выдаётся право на удержание.
 *
 * Без действующего разрешения не делает ничего — второе звено цепочки не
 * существует, пока не отработало первое. Разрешение при этом гасится: одного
 * аккорда хватает ровно на одну серию.
 */
export function completeTaps(state: GateState, now: number): GateState {
  if (!isArmed(state, now)) return state
  return { armedUntil: 0, holdUntil: now + HOLD_WINDOW_MS }
}

/**
 * Начинать ли отсчёт удержания.
 *
 * Только после тапов. Без них жеста в этот момент не существует, и показывать
 * пользователю нечего — ни отсчёта, ни намёка.
 */
export function shouldStartHold(state: GateState, now: number): boolean {
  return state.holdUntil > now
}

/** Пора ли открывать окно ключа. */
export function holdCompleted(startedAt: number, now: number, holdMs: number): boolean {
  return now - startedAt >= holdMs
}

/** Доля удержания, 0…1. По ней решается, показывать ли намёк. */
export function holdProgress(startedAt: number, now: number, holdMs: number): number {
  if (holdMs <= 0) return 1
  return Math.min(1, Math.max(0, (now - startedAt) / holdMs))
}

/** Показывать ли намёк при такой доле удержания. */
export function showsHint(progress: number): boolean {
  return progress >= HOLD_HINT_FROM
}

/* -------------------------------------------------------------------------- */
/* Второе звено: серия тапов по часам                                          */
/* -------------------------------------------------------------------------- */

/**
 * Добавляет тап к серии.
 *
 * Пауза длиннее окна начинает серию заново: человек, трогающий часы раз в
 * минуту, не должен однажды набрать пятый тап и удивиться. Храним только
 * последние `TAP_COUNT` меток — серия не растёт бесконечно.
 */
export function registerTap(previous: number[], now: number): number[] {
  const last = previous[previous.length - 1]
  const series = last !== undefined && now - last > TAP_WINDOW_MS ? [] : previous
  return [...series, now].slice(-TAP_COUNT)
}

/**
 * Набралась ли серия. Проверяется и число тапов, и общая длительность: пять
 * тапов по секунде — это не «быстро пять раз», а обычное поглядывание на часы.
 */
export function tapsArm(taps: number[]): boolean {
  return taps.length >= TAP_COUNT && taps[taps.length - 1] - taps[0] <= TAP_WINDOW_MS
}

/**
 * Лицензионный ключ установки: маска ввода и признак «набран целиком».
 *
 * Одно место на всё приложение. Ключ вводят дважды за жизнь установки, но в
 * разных экранах: при первой активации (ActivationScreen) и потом каждый раз,
 * когда приезжает специалист (окно ключа). Пока маска была написана в первом из
 * них, второму пришлось бы её скопировать — и однажды они разошлись бы в том,
 * сколько символов принимать.
 *
 * Формат задан на сервере (backend/app/modules/licensing/activation.py):
 * `KASSIR-` и двенадцать символов Crockford Base32 тремя группами по четыре.
 * Алфавит без I, L, O и U — их путают с 1, 0 и V при чтении с наклейки, а ключ
 * именно читают с наклейки и набирают руками.
 */

const PREFIX = 'KASSIR'
/** Полезная часть: 8 символов данных и 4 контрольной суммы. */
const BODY_LENGTH = 12

/**
 * Замены для символов, которых в алфавите ключа нет.
 *
 * I и L неотличимы от единицы, O — от нуля, поэтому их из алфавита и
 * исключили. Но человек читает ключ с наклейки и набирает то, что увидел: если
 * ему померещилась буква, он наберёт букву.
 *
 * Подставлять цифру безопасно ровно потому, что этих букв в настоящих ключах не
 * бывает: набранная I может быть только неверно прочитанной единицей, другого
 * толкования у неё нет. Молча выбрасывать такой символ хуже — поле не
 * реагировало бы на нажатие, и человек решил бы, что клавиатура не работает.
 *
 * U в алфавите тоже нет, и заменить её нечем — она отбрасывается остальной
 * фильтрацией, как и любой посторонний символ.
 */
const CONFUSABLES: Record<string, string> = { I: '1', L: '1', O: '0' }

/**
 * Алфавит ключа — Crockford Base32, тот же, что на сервере
 * (backend/app/modules/licensing/activation.py).
 *
 * Фильтр по нему нужен не для красоты. Окно специалиста отправляет ключ на
 * проверку само, как только он набран целиком; без фильтра «целиком набранным»
 * считался бы и ключ с посторонней буквой, который сервер отвергнет заведомо, —
 * то есть попытка из пяти тратилась бы на заранее проигранную.
 */
const ALPHABET = /[^0-9ABCDEFGHJKMNPQRSTVWXYZ]/g

/** Готовая строка целиком: `KASSIR-XXXX-XXXX-XXXX` — 21 символ. */
export const LICENSE_KEY_LENGTH = PREFIX.length + 1 + BODY_LENGTH + 2

export const LICENSE_KEY_PLACEHOLDER = 'KASSIR-____-____-____'

/**
 * Приводит набранное к маске прямо во время ввода.
 *
 * Регистр, дефисы и пробелы человек расставляет как придётся — от него это и не
 * требуется. Префикс дописывается сам: он одинаков у всех ключей, и заставлять
 * набирать его на экранной клавиатуре значит тратить шесть нажатий впустую.
 * Набранный вручную префикс при этом не задваивается.
 */
export function formatLicenseKeyInput(raw: string): string {
  let cleaned = raw.toUpperCase().replace(/[^0-9A-Z]/g, '')
  // Префикс снимается до фильтрации по алфавиту: в самом слове KASSIR есть «I»,
  // и подстановка единицы превратила бы его в «KASS1R», после чего он перестал
  // бы узнаваться и уехал бы в тело ключа.
  if (cleaned.startsWith(PREFIX)) cleaned = cleaned.slice(PREFIX.length)
  cleaned = cleaned
    .replace(/[ILO]/g, (character) => CONFUSABLES[character])
    .replace(ALPHABET, '')
    .slice(0, BODY_LENGTH)
  const groups = [cleaned.slice(0, 4), cleaned.slice(4, 8), cleaned.slice(8, 12)].filter(Boolean)
  return groups.length ? `${PREFIX}-${groups.join('-')}` : ''
}

/**
 * Набран ли ключ полностью.
 *
 * По этому признаку окно специалиста отправляет ключ на проверку само, без
 * кнопки: длина ключа известна заранее, и ждать от человека подтверждения того,
 * что и так видно, незачем. Контрольная сумма здесь не считается — её проверяет
 * сервер, и делать это дважды в разных местах значит однажды разойтись.
 */
export function isCompleteLicenseKey(value: string): boolean {
  return formatLicenseKeyInput(value).length === LICENSE_KEY_LENGTH
}

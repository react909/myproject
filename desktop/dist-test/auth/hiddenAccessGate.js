/** Пора ли открывать окно ключа. */
function holdCompleted(startedAt, now, holdMs) {
    return now - startedAt >= holdMs;
}
/** Доля удержания, 0…1. По ней решается, показывать ли намёк. */
function holdProgress(startedAt, now, holdMs) {
    if (holdMs <= 0)
        return 1;
    return Math.min(1, Math.max(0, (now - startedAt) / holdMs));
}
/** Показывать ли намёк при такой доле удержания. */
function showsHint(progress) {
    return progress >= exports.HOLD_HINT_FROM;
}

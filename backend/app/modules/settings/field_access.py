"""Кто какие реквизиты может менять.

Реквизиты — один объект, но живут в нём две разные вещи. Название магазина,
адрес, телефон и система налогообложения — это бизнес владельца: переехали или
сменили номер, и чек обязан измениться сегодня, а не когда доедет установщик.
Логотипы, номера ККМ, ширина ленты и провайдеры оплаты — это техника: её
настраивают один раз при установке, и трогать её владельцу незачем.

Отсюда разделение по полям, а не по маршрутам. Маршрут один — `PATCH
/api/settings/store`, — а набор допустимых полей зависит от того, какая дверь
открыта. Попытка прислать чужое поле отвергается явно: тихо проигнорировать
правку хуже отказа, потому что человек уходит уверенным, что сохранил.
"""

from __future__ import annotations

from app.core.elevation import DOOR_OWNER, DOOR_SPECIALIST
from app.modules.setup.schema import OnboardingData

"""Группы реквизитов, которые меняет владелец.

Всё, что печатается в чеке словами и относится к самому магазину, а не к
оборудованию: наименования, адрес, контакты, налоги, сфера и валюта, имя
владельца в роли кассира.
"""
OWNER_GROUPS = frozenset({"company", "outlet", "tax", "contacts", "owner", "business"})

"""Группы, которые меняет только специалист.

`branding` — логотипы и всё, что связано с лентой (ширина, порог, шаблон
термопечати). `acquiring` — эквайринг, провайдеры и QR. `kkm` — номера
фискального модуля с шильдика. `fiscalMode` и `edition` — режим работы и тариф:
это условия установки, а не текущие дела магазина.
"""
SPECIALIST_GROUPS = frozenset({"branding", "acquiring", "kkm", "fiscal_mode", "edition"})

"""Человеческие названия групп для сообщения об отказе.

Без них отказ выглядел бы как «поле branding недоступно» — строка из кода,
которую владелец не сопоставит ни с чем на экране.
"""
GROUP_LABELS = {
    "branding": "логотипы и оформление чека",
    "acquiring": "эквайринг и способы оплаты",
    "kkm": "реквизиты кассового аппарата",
    "fiscal_mode": "режим работы",
    "edition": "тариф",
    "company": "наименования",
    "outlet": "адрес и место расчётов",
    "tax": "налогообложение",
    "contacts": "контакты",
    "owner": "владелец",
    "business": "сфера и валюта",
}


def changed_groups(before: OnboardingData, after: OnboardingData) -> set[str]:
    """Какие группы реквизитов правка действительно меняет.

    Сравниваются значения, а не факт присутствия в запросе: интерфейс присылает
    объект целиком, и «поле пришло» не значит «поле изменили». Иначе владелец
    получал бы отказ за то, что форма отправила неизменённый логотип обратно.
    """
    old = before.model_dump()
    new = after.model_dump()
    return {key for key in new if old.get(key) != new.get(key)}


def forbidden_groups(changed: set[str], doors: set[str]) -> list[str]:
    """Что из изменённого не разрешено ни одной открытой двери."""
    allowed: set[str] = set()
    if DOOR_OWNER in doors:
        allowed |= OWNER_GROUPS
    if DOOR_SPECIALIST in doors:
        allowed |= SPECIALIST_GROUPS
    return sorted(changed - allowed)


def denial_text(groups: list[str]) -> str:
    """Отказ с указанием, что именно не прошло и к кому с этим идти."""
    names = ", ".join(GROUP_LABELS.get(group, group) for group in groups)
    return f"Эти настройки меняет специалист: {names}."

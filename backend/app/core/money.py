"""Деньги целыми числами и себестоимость — обе формулы в одном месте.

Почему тыйыны, а не float. Сом делится на 100 тыйынов, и любая сумма в кассе
выражается целым их числом. Как только та же сумма попадает в float, она
перестаёт быть точной: 0.1 + 0.2 != 0.3 и в Python тоже. На одной продаже это
незаметно, на сверке кассы за смену — уже нет: триста чеков дают ошибку в
несколько тыйынов, и кассир видит недостачу, которой не было, а закрыть смену
без объяснения расхождения нельзя.

Почему не Decimal. Он точен, но SQLite хранит его строкой или тем же float, а
складывать суммы приходится в SQL — агрегатом, а не перебором строк в Python.
Целое складывается точно в любом движке.

Граница проходит по краю модуля закупок и смен: внутри — только целые тыйыны,
наружу (в старые таблицы `sales`, `products`, где деньги во float) значение
переводится ровно один раз, здешними функциями.
"""

from __future__ import annotations

from decimal import ROUND_HALF_UP, Decimal

# Тыйынов в соме. Названо, а не вписано числом: `* 100` по коду ничего не
# объясняет, а `TIYIN_IN_SOM` объясняет.
TIYIN_IN_SOM = 100


def to_tiyin(amount: float | int | str | Decimal) -> int:
    """Сомы → тыйыны, с округлением «половину вверх».

    Через Decimal, а не `round(x * 100)`: банковское округление Python
    отправило бы 2.675 сома в 267 тыйынов вместо 268, и на чеке появилась бы
    копейка расхождения с тем, что видел кассир на экране.
    """
    quantized = Decimal(str(amount)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return int(quantized * TIYIN_IN_SOM)


def to_som(tiyin: int) -> float:
    """Тыйыны → сомы. Только для записи в старые float-колонки и в ответ API.

    Обратно в расчёт результат не возвращается: посчитали в целых — в целых и
    храним.
    """
    return int(tiyin) / TIYIN_IN_SOM


def split_evenly(total_tiyin: int, parts: int) -> list[int]:
    """Разложить сумму на равные части без потери тыйына.

    Остаток раздаётся первым частям по одному. Нужен там, где сумму документа
    надо разнести по строкам: деление нацело потеряло бы до `parts - 1`
    тыйынов, и итог перестал бы сходиться со слагаемыми.
    """
    if parts <= 0:
        return []
    base, remainder = divmod(int(total_tiyin), parts)
    return [base + (1 if index < remainder else 0) for index in range(parts)]


def weighted_average_cost(
    stock_qty: float,
    stock_cost_tiyin: int,
    incoming_qty: float,
    incoming_cost_tiyin: int,
) -> int:
    """Средневзвешенная себестоимость единицы, в тыйынах.

        (остаток × старая себестоимость + приход × цена прихода)
        ─────────────────────────────────────────────────────────
                        остаток + приход

    ЭТО ЕДИНСТВЕННОЕ МЕСТО, где формула записана. Проведение закупки, отмена
    проведения, возврат поставщику и тесты зовут её и не считают ничего сами:
    вторая копия формулы означала бы, что себестоимость на складе и
    себестоимость в отчёте однажды разойдутся, а какая из них верная — никто
    не скажет.

    Крайние случаи, и все три встречаются в жизни:

    * остаток нулевой или отрицательный (продали в минус, что SQLite позволяет)
      — берём цену прихода как есть. Взвешивать не по чему, а отрицательный
      остаток в знаменателе дал бы отрицательную себестоимость;
    * приход нулевой — себестоимость не меняется;
    * знаменатель обратился в ноль — то же самое, возвращаем цену прихода.

    Считается в Decimal: остатки бывают дробными (весовой товар), и умножение
    float на цену в тыйынах даёт хвост, который при округлении гуляет на
    тыйын туда-сюда от порядка слагаемых.
    """
    incoming = Decimal(str(incoming_qty))
    if incoming <= 0:
        return int(stock_cost_tiyin)

    stock = Decimal(str(stock_qty))
    if stock <= 0:
        return int(incoming_cost_tiyin)

    denominator = stock + incoming
    if denominator <= 0:
        return int(incoming_cost_tiyin)

    numerator = stock * Decimal(int(stock_cost_tiyin)) + incoming * Decimal(int(incoming_cost_tiyin))
    return int((numerator / denominator).quantize(Decimal("1"), rounding=ROUND_HALF_UP))


def line_total(unit_tiyin: int, qty: float) -> int:
    """Сумма строки: цена за единицу × количество, в целых тыйынах.

    Считается на сервере, а не принимается с фронта. Иначе итог документа
    зависел бы от того, как округлил браузер, и накладная на сорок строк
    расходилась бы с суммой строк на тыйын-другой — ровно та цифра, которую
    поставщик заметит первой.

    Количество бывает дробным (весовой товар), поэтому Decimal, а не float:
    2.5 кг по 3.33 сома должны дать 832 тыйына, а не 831.9999999.
    """
    value = Decimal(int(unit_tiyin)) * Decimal(str(qty))
    return int(value.quantize(Decimal("1"), rounding=ROUND_HALF_UP))


def markup_percent(cost_tiyin: int, retail_tiyin: int) -> float:
    """Наценка в процентах от закупочной цены.

    Обратная к `retail_from_markup`, и обе нужны: в таблице закупки наценка и
    розничная цена связаны в обе стороны — правишь одну, пересчитывается
    другая. При нулевой закупочной цене наценка не определена (делить не на
    что), и возвращается ноль, а не бесконечность.
    """
    if cost_tiyin <= 0:
        return 0.0
    return round((retail_tiyin - cost_tiyin) * 100 / cost_tiyin, 2)


def retail_from_markup(cost_tiyin: int, percent: float) -> int:
    """Розничная цена по закупочной и наценке, в тыйынах."""
    if cost_tiyin <= 0:
        return 0
    value = Decimal(int(cost_tiyin)) * (Decimal("1") + Decimal(str(percent)) / Decimal("100"))
    return int(value.quantize(Decimal("1"), rounding=ROUND_HALF_UP))
